export function letterPickItemsForKey(key: string): LetterPickEntry[] {
  const k = key.normalize("NFC").toLocaleLowerCase("de-DE");
  return LETTER_PICK_ITEMS.filter((it) => it.key === k);
}

export function isLetterPickPuzzle(puzzle: Puzzle): boolean {
  return puzzle.type === "letterPick";
}

function indexFromRng(rng: () => number, length: number): number {
  if (length <= 0) return 0;
  const r = rng();
  const n = Number.isFinite(r) ? r : 0;
  const u = Math.min(1, Math.max(0, n));
  return Math.min(length - 1, Math.floor(u * length));
}

function shuffleInPlace<T>(arr: T[], rng: () => number): void {
  for (let i = arr.length - 1; i > 0; i -= 1) {
    const j = indexFromRng(rng, i + 1);
    const tmp = arr[i]!;
    arr[i] = arr[j]!;
    arr[j] = tmp;
  }
}

let lastHitId = "";

export function resetLetterPickPick(): void {
  lastHitId = "";
}

export function letterPickHitId(entry: LetterPickEntry): string {
  return `${entry.key}|${entry.slug}`;
}

function pickHit(rng: () => number, avoidId: string): LetterPickEntry {
  const pool = avoidId
    ? LETTER_PICK_ITEMS.filter((it) => letterPickHitId(it) !== avoidId)
    : LETTER_PICK_ITEMS;
  const list = pool.length > 0 ? pool : LETTER_PICK_ITEMS;
  const picked = list[indexFromRng(rng, list.length)]!;
  lastHitId = letterPickHitId(picked);
  return picked;
}

/** Deterministic pick by absolute index into LETTER_PICK_ITEMS. */
export function rngForLetterPickIndex(index: number): () => number {
  const len = LETTER_PICK_ITEMS.length;
  const i = ((index % len) + len) % len;
  return () => (i + 0.5) / len;
}

function pickDistractors(
  key: string,
  hitId: string,
  count: number,
  rng: () => number,
): LetterPickEntry[] {
  const candidates = LETTER_PICK_ITEMS.filter(
    (it) => letterPickHitId(it) !== hitId && !wordContainsLetter(it.display, key),
  );
  // unique by display to avoid duplicate tiles
  const byDisplay = new Map<string, LetterPickEntry>();
  for (const it of candidates) {
    if (!byDisplay.has(it.display)) byDisplay.set(it.display, it);
  }
  const unique = [...byDisplay.values()];
  shuffleInPlace(unique, rng);
  if (unique.length < count) {
    throw new Error(`letterPick: need ${count} distractors without '${key}', got ${unique.length}`);
  }
  return unique.slice(0, count);
}

/** Fill letter, five options, and solution id from catalog. */
export function realizeLetterPickPuzzle(
  puzzle: Puzzle,
  rng: () => number = Math.random,
): Puzzle {
  if (!isLetterPickPuzzle(puzzle)) return puzzle;
  const hit = pickHit(rng, lastHitId);
  const distractors = pickDistractors(hit.key, letterPickHitId(hit), 4, rng);
  const options: LetterPickOption[] = [
    {
      id: letterPickHitId(hit),
      display: hit.display,
      artPath: hit.artPath,
      voiceText: hit.display,
    },
    ...distractors.map((d) => ({
      id: letterPickHitId(d),
      display: d.display,
      artPath: d.artPath,
      voiceText: d.display,
    })),
  ];
  shuffleInPlace(options, rng);
  const upper = hit.key.toLocaleUpperCase("de-DE");
  return {
    ...puzzle,
    solution: letterPickHitId(hit),
    voiceText: "",
    prompt: `Welches Wort hat ein ${upper}?`,
    letterPickLetter: hit.key,
    letterPickOptions: options,
    anlautVisible: false,
  };
}
