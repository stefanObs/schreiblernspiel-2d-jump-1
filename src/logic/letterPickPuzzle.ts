import type { LetterPickOption, Puzzle } from "./puzzleTypes";

export type LetterPickEntry = {
  /** Puzzle letter key a–z. */
  key: string;
  /** Display form for speech (usually noun capitalization). */
  display: string;
  /** Filename slug under letterpick/<key>/. */
  slug: string;
  /** Public path without leading slash, e.g. art/letterpick/a/affe.png */
  artPath: string;
};

export type { LetterPickOption };

/** NFC + de-DE lower; ä/ö/ü/ß stay distinct (ä≠a, ß≠s). */
export function wordContainsLetter(word: string, letter: string): boolean {
  const key = letter.normalize("NFC").toLocaleLowerCase("de-DE");
  if (!/^[a-z]$/.test(key)) return false;
  const chars = [...word.normalize("NFC").toLocaleLowerCase("de-DE")];
  return chars.includes(key);
}

function entry(key: string, display: string, slug: string): LetterPickEntry {
  return { key, display, slug, artPath: `art/letterpick/${key}/${slug}.png` };
}

